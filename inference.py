from dataclasses import dataclass
from pathlib import Path
from time import perf_counter
import networkx as nx
import numpy as np
import pandas as pd
from pgmpy.factors import factor_product
from pgmpy.factors.discrete import DiscreteFactor, State, TabularCPD
from pgmpy.inference import CausalInference, VariableElimination
from pgmpy.readwrite import BIFReader
from pgmpy.sampling import BayesianModelSampling

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "results" / "models"
STATES = ("low", "medium", "high")
METHODS = ("exact", "rejection", "likelihood_weighting", "gibbs")


class ZeroProbabilityEvidence(RuntimeError):
    """The model assigns no probability mass to the supplied evidence."""


@dataclass(frozen=True)
class Prediction:
    """Per-gene marginals and wall-clock time for one query."""

    distributions: pd.DataFrame
    runtime_seconds: float
    method: str


def load_model(network, training_set="baseline", estimator="interpolated",
               model_dir=MODEL_DIR):
    """Load one BIF network generated by ``learn.py``."""
    path = Path(model_dir) / f"network_{network}_{training_set}_{estimator}.bif"
    return BIFReader(str(path)).get_model()


def mutilate(model, do):
    """Return the intervention model formed by replacing each intervened CPT."""
    do = dict(do or {})
    mutilated = model.copy()
    for variable, state in do.items():
        if variable not in mutilated.nodes():
            raise ValueError(f"Unknown intervention variable: {variable}")
        cpd = mutilated.get_cpds(variable)
        states = list(cpd.state_names[variable])
        if state not in states:
            raise ValueError(f"Unknown state {state!r} for {variable}; expected {states}")
        mutilated.remove_edges_from(list(mutilated.in_edges(variable)))
        mutilated.remove_cpds(cpd)
        mutilated.add_cpds(TabularCPD(
            variable=variable,
            variable_card=len(states),
            values=[[1.0 if candidate == state else 0.0] for candidate in states],
            state_names={variable: states},
        ))
    mutilated.check_model()
    return mutilated


def _label(value, states):
    if value in states:
        return value
    if isinstance(value, (int, np.integer)) and 0 <= int(value) < len(states):
        return states[int(value)]
    raise ValueError(f"Sampled state {value!r} is not one of {states}")


def _probability_row(variable, states, probabilities):
    return {
        "gene": variable,
        **probabilities,
        "predicted_state": max(states, key=lambda state: probabilities[state]),
    }


def _factor_row(model, variable, factor):
    states = list(model.get_cpds(variable).state_names[variable])
    probabilities = {state: float(factor.get_value(**{variable: state})) for state in states}
    return _probability_row(variable, states, probabilities)


def _sample_rows(model, samples, weighted=False):
    if samples.empty:
        raise ZeroProbabilityEvidence("The sampler accepted no rows.")
    weights = samples["_weight"].to_numpy(float) if weighted else np.ones(len(samples))
    if not np.isfinite(weights).all() or weights.sum() <= 0:
        raise ZeroProbabilityEvidence("The model assigns zero probability to the evidence.")
    rows = []
    for variable in model.nodes():
        states = list(model.get_cpds(variable).state_names[variable])
        labels = np.array([_label(value, states) for value in samples[variable]], dtype=object)
        probabilities = {state: float(weights[labels == state].sum() / weights.sum()) for state in states}
        rows.append(_probability_row(variable, states, probabilities))
    return pd.DataFrame(rows)


def _state_codes(model, assignments):
    return [State(variable, model.get_cpds(variable).get_state_no(variable, state))
            for variable, state in assignments.items()]


def _exact(mutilated, evidence):
    engine = VariableElimination(mutilated)
    rows = []
    for variable in mutilated.nodes():
        if variable in evidence:
            states = list(mutilated.get_cpds(variable).state_names[variable])
            state = evidence[variable]
            if state not in states:
                raise ValueError(f"Unknown evidence state {state!r} for {variable}")
            probabilities = {candidate: float(candidate == state) for candidate in states}
            rows.append(_probability_row(variable, states, probabilities))
        else:
            factor = engine.query([variable], evidence=evidence, show_progress=False)
            rows.append(_factor_row(mutilated, variable, factor))
    return pd.DataFrame(rows)


def _rejection(mutilated, evidence, n_samples, seed):
    samples = BayesianModelSampling(mutilated).rejection_sample(
        evidence=[State(variable, state) for variable, state in evidence.items()],
        size=n_samples, seed=seed, show_progress=False,
    )
    return _sample_rows(mutilated, samples)


def _likelihood_weighting(mutilated, evidence, n_samples, seed):
    samples = BayesianModelSampling(mutilated).likelihood_weighted_sample(
        evidence=[State(variable, state) for variable, state in evidence.items()],
        size=n_samples, seed=seed, show_progress=False, n_jobs=1,
    )
    return _sample_rows(mutilated, samples, weighted=True)


def _gibbs_start_state(mutilated, fixed, seed, evidence):
    """Sample an exact supported starting assignment for the Gibbs chain."""
    if not evidence:
        sample = BayesianModelSampling(mutilated).forward_sample(
            size=1, seed=seed, show_progress=False,
        ).iloc[0]
        start = {
            variable: mutilated.get_cpds(variable).get_state_no(
                variable, sample[variable],
            )
            for variable in mutilated.nodes()
        }
        for variable, state in fixed.items():
            state_number = mutilated.get_cpds(variable).get_state_no(variable, state)
            if start[variable] != state_number:
                raise RuntimeError(
                    f"Forward sampling violated deterministic intervention for {variable}"
                )
        return list(start.items())
    joint = factor_product(*(cpd.to_factor() for cpd in mutilated.get_cpds()))
    if fixed:
        joint = joint.reduce(_state_codes(mutilated, fixed), inplace=False)
    mass = float(joint.values.sum())
    if not np.isfinite(mass) or mass <= 0:
        raise ZeroProbabilityEvidence("The model assigns zero probability to the evidence.")
    flat = np.random.default_rng(seed).choice(
        joint.values.size, p=joint.values.reshape(-1) / mass,
    )
    assignment = np.unravel_index(flat, joint.values.shape)
    start = {
        variable: mutilated.get_cpds(variable).get_state_no(variable, state)
        for variable, state in fixed.items()
    }
    start.update(dict(zip(joint.variables, assignment)))
    return list(start.items())


def _cpd_probability(cpd, assignment):
    states = {
        variable: cpd.state_names[variable][assignment[variable]]
        for variable in cpd.variables
    }
    return float(cpd.get_value(**states))


def _gibbs(mutilated, do, evidence, n_samples, seed, burn_in, thinning):
    if burn_in < 0 or thinning < 1:
        raise ValueError("burn_in cannot be negative and thinning must be at least 1")
    fixed = {**do, **evidence}
    variables = [variable for variable in mutilated.nodes() if variable not in fixed]
    if not variables:
        return _sample_rows(
            mutilated,
            pd.DataFrame([{variable: state for variable, state in fixed.items()}]),
        )
    current = dict(_gibbs_start_state(mutilated, fixed, seed, evidence))
    rng = np.random.default_rng(seed)
    cpds = {cpd.variable: cpd for cpd in mutilated.get_cpds()}
    children = {
        variable: [cpds[child] for child in mutilated.successors(variable)]
        for variable in variables
    }
    samples = []
    total_steps = burn_in + n_samples * thinning
    for step in range(total_steps):
        for variable in variables:
            cpd = cpds[variable]
            probabilities = np.zeros(
                cpd.variable_card, dtype=float,
            )
            for candidate in range(cpd.variable_card):
                current[variable] = candidate
                probability = _cpd_probability(cpd, current)
                for child_cpd in children[variable]:
                    probability *= _cpd_probability(child_cpd, current)
                probabilities[candidate] = probability
            total = float(probabilities.sum())
            if not np.isfinite(total) or total <= 0:
                raise ZeroProbabilityEvidence(
                    "The Gibbs chain reached an assignment with zero probability."
                )
            current[variable] = int(rng.choice(len(probabilities), p=probabilities / total))
        if step >= burn_in and (step - burn_in) % thinning == 0:
            sample = {
                variable: fixed[variable] if variable in fixed else current[variable]
                for variable in mutilated.nodes()
            }
            samples.append(sample)
    samples = pd.DataFrame(samples)
    return _sample_rows(mutilated, samples)


def predict(model, do=None, evidence=None, method="exact", n_samples=10_000,
            seed=None, burn_in=1_000, thinning=1):
    """Return P(Y | do, evidence) for every gene and the query runtime."""
    if method not in METHODS:
        raise ValueError(f"method must be one of {METHODS}")
    if n_samples < 1:
        raise ValueError("n_samples must be positive")
    do, evidence = dict(do or {}), dict(evidence or {})
    overlap = set(do) & set(evidence)
    if overlap:
        raise ValueError(f"Variables cannot be both intervened on and observed: {sorted(overlap)}")
    start = perf_counter()
    mutilated = mutilate(model, do)
    if method == "exact":
        distributions = _exact(mutilated, evidence)
    elif method == "rejection":
        distributions = _rejection(mutilated, evidence, n_samples, seed)
    elif method == "likelihood_weighting":
        distributions = _likelihood_weighting(mutilated, evidence, n_samples, seed)
    else:
        distributions = _gibbs(mutilated, do, evidence, n_samples, seed, burn_in, thinning)
    return Prediction(distributions, perf_counter() - start, method)


def probability_of_evidence(model, do=None, evidence=None):
    """Return P(evidence | do) under the mutilated model."""
    do, evidence = dict(do or {}), dict(evidence or {})
    overlap = set(do) & set(evidence)
    if overlap:
        raise ValueError(
            f"Variables cannot be both intervened on and observed: {sorted(overlap)}"
        )
    mutilated = mutilate(model, do)
    if not evidence:
        return 1.0
    for variable, state in evidence.items():
        if variable not in mutilated.nodes():
            raise ValueError(f"Unknown evidence variable: {variable}")
        states = mutilated.get_cpds(variable).state_names[variable]
        if state not in states:
            raise ValueError(
                f"Unknown evidence state {state!r} for {variable}; expected {states}"
            )
    factor = VariableElimination(mutilated).query(
        list(evidence), show_progress=False,
    )
    return float(factor.get_value(**evidence))


def compare_exact_routes(model, do, evidence=None, atol=1e-10):
    """
    Check mutilation+VE against CausalInference for its valid targets.

    Note: CausalInference cannot query an intervened variable itself because its
    implementation also inserts that variable into evidence. Its point-mass
    CPT is checked directly by ``mutilate``.  Comparison therefore skips intervened 
    variables and uses CausalInference to check the other targets, such as 
    (P(G2 | do(G1={low}))), against inference on the mutilated network.
    """
    evidence = dict(evidence or {})
    direct = predict(model, do=do, evidence=evidence, method="exact").distributions.set_index("gene")
    causal = CausalInference(model)
    blocked = set(do) | set(evidence)
    if do:
        blocked |= set().union(*(nx.ancestors(model, variable) for variable in do))
    checked = []
    for variable in model.nodes():
        if variable in blocked:
            continue
        factor = causal.query([variable], do=do, evidence=evidence, show_progress=False)
        if not isinstance(factor, DiscreteFactor):
            raise TypeError("CausalInference.query did not return a DiscreteFactor")
        expected = np.array([direct.loc[variable, state] for state in STATES])
        actual = np.array([factor.get_value(**{variable: state}) for state in STATES])
        if not np.allclose(actual, expected, atol=atol, rtol=0):
            raise AssertionError(f"CausalInference disagrees with mutilation for {variable}")
        checked.append(variable)
    return checked
